'use strict';

function analyzeCollectionsPlan(tree, helpers) {
  const { walk, findFirstIdentifierValue } = helpers;
  let hasSet = false;
  let hasMap = false;
  let hasWeakSet = false;
  let hasWeakMap = false;
  let hasArrayFrom = false;

  walk(tree, (node) => {
    if (!node || node.kind !== 'nonterminal') return;
    if (node.name === 'identifier' || node.name === 'identifierReference') {
      const name = findFirstIdentifierValue(node);
      if (name === 'Set') hasSet = true;
      else if (name === 'Map') hasMap = true;
      else if (name === 'WeakSet') hasWeakSet = true;
      else if (name === 'WeakMap') hasWeakMap = true;
      else if (name === 'from') hasArrayFrom = true;
    }
  });

  return {
    enabled: hasSet || hasMap || hasWeakSet || hasWeakMap || hasArrayFrom,
    hasSet,
    hasMap,
    hasWeakSet,
    hasWeakMap,
    hasArrayFrom
  };
}

function emitCollectionsRuntimeHelpersCpp(options = {}) {
  const hasClosurePlan = Boolean(options && options.hasClosurePlan);
  return [
    'struct __maia_collection {',
    '  int kind;',
    '  int size;',
    '  int capacity;',
    '  long* keys;',
    '  long* vals;',
    '};',
    'static void __maia_coll_ensure(__maia_collection* c, int needed) {',
    '  if (!c || needed <= c->capacity) { return; }',
    '  int new_cap = c->capacity > 0 ? c->capacity * 2 : 16;',
    '  while (new_cap < needed) { new_cap *= 2; }',
    '  long* nk = (long*)__malloc((unsigned long)(new_cap * 8));',
    '  long* nv = (long*)__malloc((unsigned long)(new_cap * 8));',
    '  for (int i = 0; i < c->size; i += 1) { nk[i] = c->keys[i]; nv[i] = c->vals[i]; }',
    '  if (c->keys) { free((void*)c->keys); }',
    '  if (c->vals) { free((void*)c->vals); }',
    '  c->keys = nk;',
    '  c->vals = nv;',
    '  c->capacity = new_cap;',
    '}',
    'static int __maia_coll_key_eq(long a, long b) {',
    '  if (a == b) { return 1; }',
    '  if (a > 4096 && b > 4096) {',
    '    const char* sa = (const char*)a;',
    '    const char* sb = (const char*)b;',
    '    if (sa && sb && strcmp(sa, sb) == 0) { return 1; }',
    '  }',
    '  return 0;',
    '}',
    'static void* __maia_set_add(void* raw, long val) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], val)) { return raw; }',
    '  }',
    '  __maia_coll_ensure(c, c->size + 1);',
    '  c->keys[c->size] = val;',
    '  c->vals[c->size] = 0;',
    '  c->size += 1;',
    '  return raw;',
    '}',
    'static int __maia_set_has(void* raw, long val) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], val)) { return 1; }',
    '  }',
    '  return 0;',
    '}',
    'static int __maia_set_delete(void* raw, long val) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], val)) {',
    '      for (int j = i + 1; j < c->size; j += 1) { c->keys[j - 1] = c->keys[j]; }',
    '      c->size -= 1;',
    '      return 1;',
    '    }',
    '  }',
    '  return 0;',
    '}',
    'static int __maia_set_size(void* raw) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  return c ? c->size : 0;',
    '}',
    'static void* __maia_set_new(void* init_arr) {',
    '  __maia_collection* c = new __maia_collection();',
    '  c->kind = 1;',
    '  c->size = 0;',
    '  c->capacity = 0;',
    '  c->keys = 0;',
    '  c->vals = 0;',
    '  if (init_arr) {',
    '    int len = __maia_runtime_value_length(init_arr);',
    '    for (int i = 0; i < len; i += 1) {',
    '      __maia_set_add((void*)c, __maia_runtime_value_get_index(init_arr, i));',
    '    }',
    '  }',
    '  return (void*)c;',
    '}',
    'static void* __maia_map_set(void* raw, long key, long val) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], key)) { c->vals[i] = val; return raw; }',
    '  }',
    '  __maia_coll_ensure(c, c->size + 1);',
    '  c->keys[c->size] = key;',
    '  c->vals[c->size] = val;',
    '  c->size += 1;',
    '  return raw;',
    '}',
    'static long __maia_map_get(void* raw, long key) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], key)) { return c->vals[i]; }',
    '  }',
    '  return 0;',
    '}',
    'static int __maia_map_has(void* raw, long key) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], key)) { return 1; }',
    '  }',
    '  return 0;',
    '}',
    'static int __maia_map_delete(void* raw, long key) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return 0; }',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    if (__maia_coll_key_eq(c->keys[i], key)) {',
    '      for (int j = i + 1; j < c->size; j += 1) {',
    '        c->keys[j - 1] = c->keys[j];',
    '        c->vals[j - 1] = c->vals[j];',
    '      }',
    '      c->size -= 1;',
    '      return 1;',
    '    }',
    '  }',
    '  return 0;',
    '}',
    'static int __maia_map_size(void* raw) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  return c ? c->size : 0;',
    '}',
    'static void* __maia_map_new(void* init_arr) {',
    '  __maia_collection* c = new __maia_collection();',
    '  c->kind = 2;',
    '  c->size = 0;',
    '  c->capacity = 0;',
    '  c->keys = 0;',
    '  c->vals = 0;',
    '  if (init_arr) {',
    '    int len = __maia_runtime_value_length(init_arr);',
    '    for (int i = 0; i < len; i += 1) {',
    '      void* pair = (void*)__maia_runtime_value_get_index(init_arr, i);',
    '      if (pair) {',
    '        __maia_map_set((void*)c, __maia_runtime_value_get_index(pair, 0), __maia_runtime_value_get_index(pair, 1));',
    '      }',
    '    }',
    '  }',
    '  return (void*)c;',
    '}',
    'static void __maia_map_forEach(void* raw, void* cb) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c || !cb) { return; }',
    ...(hasClosurePlan ? [
      '  for (int i = 0; i < c->size; i += 1) {',
      '    __maia_closure_call_i32_2(cb, (int)c->vals[i], (int)c->keys[i]);',
      '  }'
    ] : ['  (void)cb;']),
    '}',
    'static void* __maia_array_from(void* raw) {',
    '  __maia_collection* c = (__maia_collection*)raw;',
    '  if (!c) { return __maia_runtime_alloc_value(2, 0, 0, 0); }',
    '  void* arr = __maia_runtime_alloc_value(2, c->size, 0, 0);',
    '  for (int i = 0; i < c->size; i += 1) {',
    '    __maia_runtime_value_set_index(arr, i, c->keys[i]);',
    '  }',
    '  return arr;',
    '}'
  ].join('\n');
}

module.exports = {
  analyzeCollectionsPlan,
  emitCollectionsRuntimeHelpersCpp
};
